import { chromium } from "playwright-core";
const exe = "/opt/pw-browsers/chromium-1194/chrome-linux/chrome";
const browser = await chromium.launch({ executablePath: exe, args: ["--no-sandbox"] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errs = [];
page.on("console", (m) => { if (["error", "warning"].includes(m.type())) errs.push(`${m.type()}: ${m.text()}`); });
page.on("pageerror", (e) => errs.push("pageerror: " + e.message));
const base = "http://127.0.0.1:5199/";
const shot = async (name) => { await page.waitForTimeout(450); await page.screenshot({ path: `shots/${name}.png` }); };
await page.goto(base, { waitUntil: "networkidle" });
await page.evaluate(() => localStorage.clear());
await page.goto(base + "#/home", { waitUntil: "networkidle" });
await page.waitForTimeout(800);
await shot("01-home");
await page.goto(base + "#/chapter/overview", { waitUntil: "networkidle" });
await shot("02-overview");
await page.goto(base + "#/chapter/planes", { waitUntil: "networkidle" });
await shot("03-planes");
await page.goto(base + "#/chapter/overview?p=lab%3Amoe", { waitUntil: "networkidle" });
await shot("04-overview-pane-moe");
await page.keyboard.press("Control+k");
await page.keyboard.type("pack 10");
await shot("05-palette");
await page.keyboard.press("Escape");
await page.goto(base + "#/chapter/governor", { waitUntil: "networkidle" });
await shot("06-governor");
console.log(errs.length ? errs.join("\n") : "no console errors");
await browser.close();
