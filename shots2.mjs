import { chromium } from "playwright-core";
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium-1194/chrome-linux/chrome", args: ["--no-sandbox"] });
const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
const base = "http://127.0.0.1:5199/";
const shot = async (n) => { await page.waitForTimeout(500); await page.screenshot({ path: `shots/${n}.png` }); };
const go = async (h) => { await page.goto(base + h, { waitUntil: "networkidle" }); await page.waitForTimeout(300); };
await go("#/home"); await page.evaluate(() => localStorage.clear()); await go("#/home");
await shot("01-home");
await go("#/chapter/overview"); await shot("02-chapter-overview");
